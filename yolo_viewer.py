#!/usr/bin/env python3
"""Display the latest annotated image produced by the YOLO bridge node.

The bridge writes ``yolo_overlay.png`` atomically.  This viewer watches that
file and refreshes the OpenCV window whenever a new result is available.  It
does not load the ONNX model or run a second inference process.
"""

from __future__ import annotations

import argparse
import signal
import sys
from pathlib import Path

import cv2
import numpy as np


PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_SHARED_DIR = PROJECT_ROOT / "shared_camera_data"
WINDOW_NAME = "YOLOv8-Seg - Recognition View"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Show the detection boxes and instance masks generated by YOLO."
    )
    parser.add_argument(
        "--shared-dir",
        type=Path,
        default=DEFAULT_SHARED_DIR,
        help=f"YOLO/GraspNet shared directory (default: {DEFAULT_SHARED_DIR})",
    )
    parser.add_argument(
        "--refresh-ms",
        type=int,
        default=100,
        help="File polling and GUI refresh interval in milliseconds (default: 100)",
    )
    parser.add_argument("--width", type=int, default=1060, help="Initial window width")
    parser.add_argument("--height", type=int, default=600, help="Initial window height")
    parser.add_argument(
        "--fullscreen", action="store_true", help="Open the recognition view fullscreen"
    )
    args = parser.parse_args()
    if args.refresh_ms < 10:
        parser.error("--refresh-ms must be at least 10")
    if args.width <= 0 or args.height <= 0:
        parser.error("--width and --height must be positive")
    return args


def waiting_image(width: int, height: int) -> np.ndarray:
    """Create a placeholder while the first YOLO result is pending."""
    canvas = np.full((height, width, 3), 28, dtype=np.uint8)
    cv2.putText(
        canvas,
        "Waiting for YOLO overlay...",
        (max(20, width // 2 - 230), max(50, height // 2)),
        cv2.FONT_HERSHEY_SIMPLEX,
        1.0,
        (220, 220, 220),
        2,
        cv2.LINE_AA,
    )
    return canvas


def read_image(path: Path) -> np.ndarray | None:
    """Read one complete PNG; atomic writer replacement prevents partial frames."""
    try:
        encoded = np.fromfile(path, dtype=np.uint8)
    except OSError:
        return None
    if encoded.size == 0:
        return None
    return cv2.imdecode(encoded, cv2.IMREAD_COLOR)


def main() -> int:
    args = parse_args()
    overlay_path = args.shared_dir.expanduser().resolve() / "yolo_overlay.png"
    running = True

    def request_stop(_signum: int, _frame: object) -> None:
        nonlocal running
        running = False

    signal.signal(signal.SIGINT, request_stop)
    signal.signal(signal.SIGTERM, request_stop)

    try:
        cv2.namedWindow(WINDOW_NAME, cv2.WINDOW_NORMAL | cv2.WINDOW_KEEPRATIO)
        cv2.resizeWindow(WINDOW_NAME, args.width, args.height)
        if args.fullscreen:
            cv2.setWindowProperty(WINDOW_NAME, cv2.WND_PROP_FULLSCREEN, cv2.WINDOW_FULLSCREEN)
    except cv2.error as exc:
        print(f"Unable to create the YOLO window: {exc}", file=sys.stderr)
        print("Run this script from the graphical desktop session with DISPLAY set.", file=sys.stderr)
        return 2

    print(f"Watching: {overlay_path}")
    print("Press Q or Esc in the image window to close it.")

    last_signature: tuple[int, int] | None = None
    current_image = waiting_image(args.width, args.height)
    cv2.imshow(WINDOW_NAME, current_image)

    try:
        while running:
            try:
                stat = overlay_path.stat()
                signature = (stat.st_mtime_ns, stat.st_size)
            except FileNotFoundError:
                signature = None
            except OSError as exc:
                print(f"Cannot inspect {overlay_path}: {exc}", file=sys.stderr)
                signature = None

            if signature is not None and signature != last_signature:
                image = read_image(overlay_path)
                if image is not None:
                    current_image = image
                    last_signature = signature

            cv2.imshow(WINDOW_NAME, current_image)
            key = cv2.waitKey(args.refresh_ms) & 0xFF
            if key in (ord("q"), ord("Q"), 27):
                break
            try:
                # OpenCV's Ubuntu GTK3 backend reports WND_PROP_VISIBLE=-1
                # even for a healthy, mapped window.  getWindowImageRect is
                # supported by that backend and returns a negative-size rect
                # only after the user closes the window.
                _x, _y, window_width, window_height = cv2.getWindowImageRect(WINDOW_NAME)
                if window_width < 1 or window_height < 1:
                    break
            except cv2.error:
                break
    finally:
        cv2.destroyAllWindows()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
